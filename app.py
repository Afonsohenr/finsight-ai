
import streamlit as st
import pandas as pd
import plotly.express as px

from financial_data import get_financial_data, COMPANIES

from financial_analysis import generate_financial_analysis

from ai_analyst import generate_ai_report


st.set_page_config(
    page_title="FinSight AI",
    page_icon="📊",
    layout="wide"
)


st.title("📊 FinSight AI")

st.markdown(
    """
    **AI-Powered Financial Statement Analysis**

    Analyze publicly traded companies using financial
    statements from the U.S. Securities and Exchange
    Commission (SEC).

    Explore revenue trends, profitability, financial
    ratios, and AI-generated insights.
    """
)

st.caption(
    "Data Source: SEC EDGAR | "
    "AI Analysis: Google Gemini | "
    "Built with Python & Streamlit"
)

st.divider()


# Select company
selected_company = st.selectbox(
    "Select Company",
    list(COMPANIES.keys())
)

# Retrieve real SEC financial statements
@st.cache_data(ttl=3600)
def load_data(company):
    return get_financial_data(company)


try:
    company_name, df, accession = load_data(selected_company)

except Exception as error:
    st.error("Unable to retrieve SEC financial data.")
    st.exception(error)
    st.stop()

st.success(f"Loaded real financial data for {company_name}")

st.caption(
    f"Source: SEC EDGAR | Filing: {accession} | "
    "Financial amounts in USD millions"
)


df["Revenue Growth (%)"] = df["Revenue"].pct_change() * 100
df["Operating Margin (%)"] = (
    df["Operating Income"] / df["Revenue"] * 100
)
df["Net Margin (%)"] = (
    df["Net Income"] / df["Revenue"] * 100
)

year = st.selectbox("Select Fiscal Year", df["Year"])

selected = df[df["Year"] == year].iloc[0]

col1, col2, col3 = st.columns(3)


col1.metric(
    "Revenue",
    f"${selected['Revenue']/1000:,.2f}B"
)

col2.metric(
    "Net Income",
    f"${selected['Net Income']/1000:,.2f}B"
)

col3.metric(
    "Operating Margin",
    f"{selected['Operating Margin (%)']:.2f}%"
)

st.subheader("Financial Performance")



# Financial performance chart in USD billions
chart_df = df[
    ["Year", "Revenue", "Operating Income", "Net Income"]
].copy()

for metric in ["Revenue", "Operating Income", "Net Income"]:
    chart_df[metric] = chart_df[metric] / 1000

fig = px.line(
    chart_df,
    x="Year",
    y=["Revenue", "Operating Income", "Net Income"],
    markers=True,
    title=f"{company_name} — Financial Performance",
    labels={
        "Year": "Fiscal Year",
        "value": "USD Billions",
        "variable": "Financial Metric"
    }
)

fig.update_xaxes(
    tickmode="array",
    tickvals=chart_df["Year"].tolist()
)

fig.update_traces(
    hovertemplate="$%{y:,.2f}B<extra>%{fullData.name}</extra>"
)

fig.update_layout(
    hovermode="x unified",
    legend_title_text="Financial Metric"
)

st.plotly_chart(fig, width="stretch")


# Display only whole fiscal years
fig.update_xaxes(
    tickmode="array",
    tickvals=df["Year"].tolist()
)

st.subheader("Financial Data")
st.dataframe(df.round(2), hide_index=True)

st.download_button(
    "Download Financial Report",
    df.to_csv(index=False),
    "financial_report.csv",
    "text/csv"
)

st.caption(
    "Financial data retrieved from SEC EDGAR. "
    "AI-generated analysis is for educational purposes."
)

# Automated financial analysis
st.divider()

st.subheader("Financial Analyst Insights")

st.caption(
    "Automated analysis based on SEC financial data. "
    "These insights are rule-based, not yet generated by AI."
)

if st.button("Generate Financial Analysis"):

    insights = generate_financial_analysis(df, year)

    for i, insight in enumerate(insights, start=1):
        st.write(f"**Insight {i}:** {insight}")


# AI Financial Analyst
st.divider()
st.subheader("AI Financial Analyst")

st.caption(
    "AI-generated financial analysis using SEC-derived financial data."
)

if st.button("Generate AI Financial Report"):
    api_key = st.secrets.get("GEMINI_API_KEY")

    if not api_key:
        st.error("Gemini API key is missing.")

    else:
        with st.spinner("AI is analyzing financial data..."):
            try:
                report = generate_ai_report(
                    df,
                    year,
                    company_name,
                    api_key
                )

                st.markdown(report)

                st.download_button(
                    "Download AI Report",
                    data=report,
                    file_name=f"finsight_ai_{year}.md",
                    mime="text/markdown"
                )

            except Exception as error:
                st.error("Unable to generate AI report.")
                st.write(
                    "Error type:",
                    type(error).__name__
                )
                st.write(
                    "Status code:",
                    getattr(error, "code", "Unknown")
                )

# Company Comparison
st.divider()
st.subheader("Company Comparison")

st.caption(
    "Compare the latest available annual financial "
    "results for two companies."
)

col1, col2 = st.columns(2)

with col1:
    company_a = st.selectbox(
        "First Company",
        list(COMPANIES.keys()),
        index=0,
        key="company_a"
    )

with col2:
    company_b = st.selectbox(
        "Second Company",
        list(COMPANIES.keys()),
        index=1,
        key="company_b"
    )


if "show_comparison" not in st.session_state:
    st.session_state.show_comparison = False

if st.button("Compare Companies"):
    st.session_state.show_comparison = True

if st.session_state.show_comparison:


    if company_a == company_b:
        st.warning("Please select two different companies.")

    else:
        try:
            name_a, df_a, _ = load_data(company_a)
            name_b, df_b, _ = load_data(company_b)

            
            # Find fiscal years available for both companies
            common_years = sorted(
                set(df_a["Year"]) & set(df_b["Year"]),
                reverse=True
            )

            if not common_years:
                st.warning(
                    "These companies have no matching fiscal years."
                )
                st.stop()

            comparison_year = st.selectbox(
                "Select Comparison Fiscal Year",
                common_years,
                key="comparison_year"
            )

            a = df_a[
                df_a["Year"] == comparison_year
            ].iloc[0]

            b = df_b[
                df_b["Year"] == comparison_year
            ].iloc[0]

            comparison = pd.DataFrame({
                
                "Metric": [
                    "Fiscal Year",
                    "Period Start",
                    "Period End",
                    "Revenue ($B)",
                    "Revenue Growth (%)",
                    "Operating Margin (%)",
                    "Net Margin (%)"
                ],
                name_a: [
                    int(a["Year"]),
                    a["Period Start"],
                    a["Period End"],
                    round(a["Revenue"] / 1000, 2),
                    round(a["Revenue Growth (%)"], 2),
                    round(a["Operating Margin (%)"], 2),
                    round(a["Net Margin (%)"], 2)
                ],
                name_b: [
                    int(b["Year"]),
                    b["Period Start"],
                    b["Period End"],
                    round(b["Revenue"] / 1000, 2),
                    round(b["Revenue Growth (%)"], 2),
                    round(b["Operating Margin (%)"], 2),
                    round(b["Net Margin (%)"], 2)
                ]
            })
            st.dataframe(
                comparison,
                hide_index=True,
                width="stretch"
            )
            if (
                a["Period Start"] != b["Period Start"]
                or a["Period End"] != b["Period End"]
            ):
                st.info(
                    "These companies have different fiscal "
                    "reporting periods. Comparisons should "
                    "be interpreted with this difference in mind."
                )

            # Compare financial ratios visually
            chart_data = pd.DataFrame({
                "Metric": [
                    "Revenue Growth",
                    "Operating Margin",
                    "Net Margin"
                ],
                name_a: [
                    a["Revenue Growth (%)"],
                    a["Operating Margin (%)"],
                    a["Net Margin (%)"]
                ],
                name_b: [
                    b["Revenue Growth (%)"],
                    b["Operating Margin (%)"],
                    b["Net Margin (%)"]
                ]
            })

            chart_data = chart_data.melt(
                id_vars="Metric",
                var_name="Company",
                value_name="Percentage"
            )

            comparison_fig = px.bar(
                chart_data,
                x="Metric",
                y="Percentage",
                color="Company",
                barmode="group",
                title="Financial Ratio Comparison",
                labels={"Percentage": "Percentage (%)"}
            )

            st.plotly_chart(
                comparison_fig,
                width="stretch",
                key="comparison_chart"
            )
            


        except Exception as error:
            st.error("Unable to compare companies.")
            st.write(type(error).__name__)
